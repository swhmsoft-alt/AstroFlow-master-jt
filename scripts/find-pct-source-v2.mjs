import { readFileSync, readdirSync, statSync } from 'fs';
import { join, dirname, extname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..', 'src');

function walk(dir, results) {
  const items = readdirSync(dir);
  for (const item of items) {
    const fp = join(dir, item);
    const st = statSync(fp);
    if (st.isDirectory()) {
      walk(fp, results);
    } else if (st.isFile() && (item.endsWith('.astro') || item.endsWith('.tsx') || item.endsWith('.ts') || item.endsWith('.css'))) {
      try {
        const c = readFileSync(fp, 'utf-8');
        if (c.includes('12.5%') || c.includes('16.67%')) {
          results.push(fp + ': ' + c.substring(Math.max(0, c.indexOf('12.5%') - 30), c.indexOf('12.5%') + 30));
        }
      } catch(e) {}
    }
  }
}

const results = [];
walk(root, results);
if (results.length === 0) {
  console.log('No source matches found in src/');
  // Check if these come from node_modules tailwind
  console.log('Checking node_modules/tailwindcss...');
  const twPath = join(__dirname, '..', 'node_modules', 'tailwindcss');
  if (require('fs').existsSync(twPath)) {
    const twFiles = ['src/lib/css/preflight.css', 'stubs/defaultConfig.stub.js'];
    twFiles.forEach(f => {
      try {
        const c = readFileSync(join(twPath, f), 'utf-8');
        if (c.includes('12.5') || c.includes('16.67')) console.log('Found in tailwind ' + f);
      } catch(e) {}
    });
  }
  // Check if it's from the Tailwind JIT compiler generating these as arbitrary values
  console.log('These are likely generated by Tailwind JIT from user classes like left-[12.5%]');
}
results.forEach(r => console.log(r));
